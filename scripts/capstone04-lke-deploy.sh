#!/usr/bin/env bash
# TWN Capstone 04 Lesson 22: deploy exactly 11 Online Boutique microservices to LKE.
set -Eeuo pipefail
readonly KCFG="${HOME}/.kube/twn-capstone04-lke.yaml"
readonly NS="online-shop"
readonly LABEL="twn-capstone04-lke"
readonly EXPECTED_ID="676998"
readonly SOURCE_SHA="218ba3dcef1d19821711e62996162f8b29c55be4"
readonly SRC="https://raw.githubusercontent.com/asambataiden/twn-devops-bootcamp-10-kubernetes-deploying-microservices-demo/${SOURCE_SHA}/release/kubernetes-manifests.yaml"
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
check() {
  local c
  for c in kubectl curl awk jq linode-cli; do command -v "$c" >/dev/null || die "Missing: $c"; done
  [[ -f "$KCFG" ]] || die "Missing isolated LKE kubeconfig"
  local id
  id="$(linode-cli lke clusters-list --json | jq -r --arg n "$LABEL" '[.[] | select(.label==$n and .region=="eu-central") | .id] | if length==1 then .[0] else empty end')"
  [[ "$id" == "$EXPECTED_ID" ]] || die "Expected LKE cluster ID $EXPECTED_ID; found ${id:-none}. Refusing to target another cluster"
  local host
  host="$(kubectl --kubeconfig "$KCFG" config view --minify -o json | jq -r '.clusters[0].cluster.server')"
  [[ "$host" == https://*.linodelke.net:* ]] || die "Unexpected kubeconfig API endpoint: $host"
  kubectl --kubeconfig "$KCFG" get nodes >/dev/null || die "LKE API unreachable"
}
render() {
  local source="$1" target="$2"
  # The pinned upstream release contains loadgenerator Deployment and
  # frontend-external LoadBalancer: both outside the 11-service exercise.
  # YAML docs are split only at standalone --- lines.
  awk '
    function emit() {
      if (doc == "") return
      if (doc ~ /kind: Deployment/ && doc ~ /name: loadgenerator/) {doc="";return}
      if (doc ~ /kind: Service/ && doc ~ /name: frontend-external/) {doc="";return}
      printf "%s", doc; doc=""
    }
    /^---[[:space:]]*$/ { emit(); doc="---\n"; next }
    {doc = doc $0 "\n"}
    END {emit()}
  ' "$source" > "$target"
  local ndep nsvc
  ndep="$(grep -c '^kind: Deployment$' "$target")"
  nsvc="$(grep -c '^kind: Service$' "$target")"
  [[ "$ndep" -eq 11 && "$nsvc" -eq 11 ]] || die "Expected 11 Deployments + 11 Services, found $ndep/$nsvc"
  ! grep -Eq 'name: (frontend-external|loadgenerator)' "$target" || die "Unexpected excluded resource"
}
with_manifest() (
  local action="$1" original filtered
  original="$(mktemp)"
  filtered="$(mktemp)"
  trap 'rm -f "$original" "$filtered"' EXIT
  curl --fail --location --silent --show-error --retry 3 "$SRC" -o "$original" || die "Pinned release download failed"
  grep -Fq 'WARNING: This file is autogenerated' "$original" || die "Unexpected release source"
  render "$original" "$filtered"
  printf 'Verified pinned release %s: 11 Deployments and 11 Services (no public LB).\n' "$SOURCE_SHA"
  [[ "$action" != "render" ]] || return 0
  check
  kubectl --kubeconfig "$KCFG" -n "$NS" get ns "$NS" >/dev/null || die "Namespace missing. Run: bash scripts/capstone04-lke-deploy.sh namespace"
  kubectl --kubeconfig "$KCFG" -n "$NS" apply --dry-run=server --validate=strict -f "$filtered"
  [[ "$action" == "plan" ]] && return 0
  [[ -t 0 ]] || die "Interactive terminal required"
  local confirm
  printf 'Type DEPLOY-LKE-676998 to deploy 11 microservices: '
  read -r confirm
  [[ "$confirm" == "DEPLOY-LKE-676998" ]] || die "Cancelled"
  kubectl --kubeconfig "$KCFG" -n "$NS" apply --validate=strict -f "$filtered"
  printf 'Deployment requested. Inspect rollout via status.\n'
)
namespace() {
  check
  kubectl --kubeconfig "$KCFG" get namespace "$NS" >/dev/null 2>&1 && { printf 'Namespace already exists.\n'; return; }
  local confirm
  printf 'Type NAMESPACE-LKE-676998 to create namespace %s: ' "$NS"
  read -r confirm
  [[ "$confirm" == "NAMESPACE-LKE-676998" ]] || die "Cancelled"
  kubectl --kubeconfig "$KCFG" create namespace "$NS"
}
status() {
  check
  kubectl --kubeconfig "$KCFG" -n "$NS" get deployments,pods,services
}
case "${1:-}" in
  render) with_manifest render ;;
  namespace) namespace ;;
  plan) with_manifest plan ;;
  deploy) with_manifest deploy ;;
  status) status ;;
  *) printf 'Usage: bash %s {render|namespace|plan|deploy|status}\n' "$0"; exit 2 ;;
esac
